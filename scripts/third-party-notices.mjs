#!/usr/bin/env node
// Writes THIRD_PARTY_NOTICES.md: the license of every package the extension ships (bundled into dist/ or, for
// playwright-core, shipped as is). Their MIT, BSD and Apache licenses require the notice to travel with the code.
//   node scripts/third-party-notices.mjs          write the file
//   node scripts/third-party-notices.mjs --check  exit 1 if the file is missing or out of date (used when packaging)
import { spawnSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'THIRD_PARTY_NOTICES.md');

// A fixed command string: npm is npm.cmd on Windows, which only a shell can run.
const ls = spawnSync('npm ls --omit=dev --all --parseable', { cwd: root, encoding: 'utf8', shell: true });
if (ls.status !== 0) {
  process.stderr.write(`npm ls failed:\n${ls.stderr}\n`);
  process.exit(1);
}
const dirs = [...new Set(ls.stdout.split(/\r?\n/).filter(Boolean))].filter((d) => relative(root, d).split(sep).includes('node_modules'));

const packages = dirs.map((dir) => {
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  // LICENSE, LICENCE.md, COPYING, LICENSE-MIT.txt…
  const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)([-.][\w-]+)?(\.(md|txt))?$/i.test(f));
  const notice = readdirSync(dir).find((f) => /^notice(\.(md|txt))?$/i.test(f));
  const text = [file, notice].filter(Boolean).map((f) => readFileSync(join(dir, f), 'utf8').trim()).join('\n\n');
  if (!text) throw new Error(`${pkg.name} ships no license file; add its license text by hand before releasing.`);
  return { name: pkg.name, version: pkg.version, license: pkg.license ?? 'see text', text };
});
packages.sort((a, b) => a.name.localeCompare(b.name));

const body = [
  '# Third-party notices',
  '',
  'OWUI Agent includes the following packages. This file is generated by `npm run notices`; do not edit it by hand.',
  '',
  ...packages.map((p) => `- ${p.name} ${p.version} (${p.license})`),
  '',
  ...packages.flatMap((p) => [`## ${p.name} ${p.version}`, '', `License: ${p.license}`, '', '```text', p.text.replace(/\r\n/g, '\n'), '```', '']),
].join('\n');

if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== body) {
    process.stderr.write('THIRD_PARTY_NOTICES.md is missing or out of date. Run `npm run notices` and commit the result.\n');
    process.exit(1);
  }
  process.stdout.write(`THIRD_PARTY_NOTICES.md is up to date (${packages.length} packages).\n`);
} else {
  writeFileSync(target, body);
  process.stdout.write(`Wrote THIRD_PARTY_NOTICES.md (${packages.length} packages).\n`);
}
